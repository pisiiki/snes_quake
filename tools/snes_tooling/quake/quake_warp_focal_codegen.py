"""Bake the fixed source focal length into the existing HDMA exponent lookup."""
from pathlib import Path
import math
import json
import hashlib

from snes_tooling.quake.quake_rom_config import configured_warp_source_focal


def config_path(example: Path) -> Path:
    root = example.resolve().parents[1]
    receipt = example/'Data/QuakeBSPAssetChain.json'
    if receipt.is_file():
        binding = json.loads(receipt.read_text(encoding='utf-8'))['config']
        if binding['external']:
            raise ValueError('external ROM configuration requires --config for runtime code generation')
        candidates = (root/binding['path'], example/binding['path'])
        for candidate in candidates:
            candidate = candidate.resolve()
            if candidate.is_relative_to(root) and candidate.is_file():
                return candidate
    return root/'config/rom-config.json'


def source_focal(example: Path, config: Path | None = None) -> int:
    return configured_warp_source_focal(config or config_path(example))


def generate(example: Path, *, check=False, config=None):
    config = config or config_path(example)
    focal = source_focal(example, config)
    intrinsics = ('; Generated from ROM config warp.sourceFocal; zoom = 64/sourceFocal.\n'
                  f'BSP_WARP_SOURCE_FOCAL = {focal}\n')
    header = example/'quake/WarpFocalConfig.i'
    config_changed = not header.is_file() or header.read_text(encoding='utf-8') != intrinsics
    if config_changed:
        if check:
            raise ValueError(f'{header.name} is stale for ROM configuration')
        header.write_text(intrinsics, encoding='utf-8', newline='\n')
    values = tuple(round(2**(i/1024) * focal/64) for i in range(15360))
    minimum = math.ceil(-1024 - 1024*math.log2(focal/64))
    lines = ['; Generated by quake_runtime_codegen.py. No runtime focal correction.',
             f'.assert BSP_WARP_SOURCE_FOCAL = {focal}, error, "Regenerate focal tables"',
             f'WARP_FOCAL_EXP_MINIMUM = {minimum}', '.segment "HDMA_OVERSCAN_EXP"',
             'HdmaOverscanExp:']
    for first in range(0, len(values), 16):
        lines.append('        .word ' + ', '.join(f'${v:04X}' for v in values[first:first+16]))
    payload = '\n'.join(lines)+'\n'
    path = example/'quake/WarpFocalTables.s'
    changed = not path.is_file() or path.read_text(encoding='utf-8') != payload
    if changed:
        if check:
            raise ValueError(f'{path.name} is stale')
        path.write_text(payload, encoding='utf-8', newline='\n')
    return {'sourceFocal': focal, 'zoomNumerator': 64, 'zoomDenominator': focal,
            'changed': changed or config_changed, 'bytes': 2*len(values),
            'configSha256': hashlib.sha256(config.read_bytes()).hexdigest()}
